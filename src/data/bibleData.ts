    "content": "예레미야는 말씀을 먹었을 때 마음의 즐거움과 환희가 되었다(렘 15:16). 에스겔이 두루마리를 먹었을 때 꿀같이 달콤하였다(겔 3:3). 요한이 받은 작은 책도 입에서는 꿀처럼 달았으나 배에서는 쓰라렸으니(계 10:10), 말씀은 달콤하지만 그 깊이를 소화하는 것은 어렵다. 하나님의 말씀은 불 같고 바위를 산산조각 내는 망치 같다(렘 23:29). 하나님의 입에서 나가는 말씀은 헛되이 돌아오지 않고 반드시 형통하며 그분이 기뻐하시는 것을 이행한다(사 55:10~11)."
